#!/usr/bin/env python3
"""Assemble current sites and centrally managed redirects into an owned _site tree."""

import argparse
import html
import json
from pathlib import Path, PurePosixPath
import re
import shutil
import stat
import tempfile


SITES = {"color-picker": "HDR Color Picker", "perceptual-grade": "Perceptual Grade"}
OWNER_FILE = ".build-site-owned"
OWNER_TEXT = "Generated by tools/build_site.py; safe to rebuild.\n"


def _json(value):
    return (json.dumps(value, ensure_ascii=True, sort_keys=True)
            .replace("<", "\\u003c").replace(">", "\\u003e").replace("&", "\\u0026"))


def _page(title, body, head=""):
    return ("<!doctype html>\n<html lang=\"en\"><head><meta charset=\"utf-8\">\n"
            '<meta name="viewport" content="width=device-width, initial-scale=1">\n'
            "<title>" + html.escape(title) + "</title>\n" + head
            + "</head><body>" + body + "</body></html>\n")


def _site_links():
    return "<ul>" + "".join(
        '<li><a href="/' + name + '/">' + html.escape(title) + "</a></li>"
        for name, title in SITES.items()) + "</ul>"


def redirect_page(target):
    escaped = html.escape(target, quote=True)
    return _page(
        "Page moved",
        '<p>This page has moved to <a href="' + escaped + '">' + escaped + "</a>.</p>",
        '<link rel="canonical" href="' + escaped + '">\n'
        + "<script>window.location.replace(" + _json(target)
        + " + window.location.search + window.location.hash);</script>\n"
        + '<meta http-equiv="refresh" content="0; url=' + escaped + '">\n',
    )


def not_found_page(redirects):
    # Exact old pages override directory rules. Prefix rules match a complete
    # path component, including a directory URL without its trailing slash.
    script = """<script>
const redirects = REDIRECT_MAP;
const pathname = window.location.pathname;
let target = Object.prototype.hasOwnProperty.call(redirects, pathname)
  ? redirects[pathname] : null;
if (target === null) {
  const prefixes = Object.keys(redirects).filter(path => path.endsWith('/'))
    .sort((left, right) => right.length - left.length);
  for (const prefix of prefixes) {
    if (pathname === prefix.slice(0, -1) || pathname.startsWith(prefix)) {
      target = redirects[prefix];
      break;
    }
  }
}
if (target !== null) {
  window.location.replace(target + window.location.search + window.location.hash);
}
</script>
""".replace("REDIRECT_MAP", _json(redirects))
    return _page("Page not found", "<h1>Page not found</h1>"
                 "<p>The requested page is unavailable. Current projects:</p>" + _site_links(), script)


def _url_path(value):
    if (not isinstance(value, str) or not re.fullmatch(r"/[A-Za-z0-9._~/-]+", value)
            or "//" in value or any(part in {".", ".."} for part in value.split("/"))
            or any(part.casefold() == ".git" for part in value.split("/"))):
        raise ValueError("Redirects require canonical local URL paths: " + repr(value))
    if not (value.endswith("/") or value.endswith(".html")):
        raise ValueError("Redirect paths must end in / or .html: " + value)
    return value


def _output_path(url):
    relative = PurePosixPath(url.lstrip("/"))
    return relative / "index.html" if url.endswith("/") else relative


def _unique_object(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError("Duplicate redirect source: " + key)
        result[key] = value
    return result


def _redirects(source, stage):
    redirects = json.loads((source / "redirects.json").read_text(encoding="utf-8"),
                           object_pairs_hook=_unique_object)
    if not isinstance(redirects, dict):
        raise ValueError("redirects.json must map old URL paths to current URL paths")
    outputs = set()
    for old, new in redirects.items():
        _url_path(old)
        _url_path(new)
        output = _output_path(old)
        target = _output_path(new)
        if target.parts[0] not in SITES or not stage.joinpath(*target.parts).is_file():
            raise ValueError("Redirect target is not a current site page: " + new)
        if output in outputs:
            raise ValueError("Redirects generate the same output: " + old)
        outputs.add(output)
        path = stage.joinpath(*output.parts)
        if path.exists() or any(parent.is_file() for parent in path.parents):
            raise ValueError("Redirect would replace current site content: " + old)
        for prefix in redirects:
            if new == prefix or (prefix.endswith("/") and new.startswith(prefix)):
                raise ValueError("Redirect targets must not point into another redirect: " + new)
    for output in outputs:
        if any(parent in outputs for parent in output.parents):
            raise ValueError("Redirect output file/directory conflict: " + str(output))
    return dict(sorted(redirects.items()))


def _copy_site(source, stage, name):
    root = source / name
    if root.is_symlink() or not root.is_dir() or not (root / "index.html").is_file():
        raise ValueError("Missing regular site directory with index.html: " + name)
    for path in [root, *sorted(root.rglob("*"))]:
        relative = path.relative_to(source)
        if path.is_symlink() or any(part.casefold() == ".git" for part in relative.parts):
            raise ValueError("Site contains a symlink or Git metadata: " + str(relative))
        mode = path.stat().st_mode
        target = stage / relative
        if stat.S_ISDIR(mode):
            target.mkdir(parents=True, exist_ok=True)
        elif stat.S_ISREG(mode):
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(path, target)
        else:
            raise ValueError("Site contains a special file: " + str(relative))


def build_site(source):
    source = Path(source).expanduser().absolute()
    if any(path.is_symlink() for path in (source, *source.parents)):
        raise ValueError("Source checkout must not pass through a symlink")
    source = source.resolve(strict=True)
    if not source.is_dir():
        raise ValueError("Source checkout must be a directory")
    output = source / "_site"
    marker = output / OWNER_FILE
    if output.is_symlink() or (output.exists() and (
            not output.is_dir() or marker.is_symlink() or not marker.is_file()
            or marker.read_text(encoding="utf-8") != OWNER_TEXT)):
        raise ValueError("Refusing to replace _site without this builder's ownership marker")
    with tempfile.TemporaryDirectory(prefix=".site-build-", dir=source) as temporary:
        temporary = Path(temporary)
        stage = temporary / "site"
        stage.mkdir()
        for name in SITES:
            _copy_site(source, stage, name)
        (stage / "index.html").write_text(_page("Projects", "<h1>Projects</h1>" + _site_links()), encoding="utf-8")
        (stage / ".nojekyll").write_bytes(b"")
        (stage / OWNER_FILE).write_text(OWNER_TEXT, encoding="utf-8")
        # Reserve the root error page before validating aliases for collisions.
        (stage / "404.html").write_text("", encoding="utf-8")
        redirects = _redirects(source, stage)
        for old, target in redirects.items():
            path = stage.joinpath(*_output_path(old).parts)
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(redirect_page(target), encoding="utf-8")
        (stage / "404.html").write_text(not_found_page(redirects), encoding="utf-8")
        previous = temporary / "previous"
        if output.exists():
            output.rename(previous)
        try:
            stage.rename(output)
        except OSError:
            if previous.exists():
                previous.rename(output)
            raise
    return output


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=Path(__file__).resolve().parents[1],
                        help="Website checkout to assemble (default: %(default)s)")
    args = parser.parse_args(argv)
    try:
        output = build_site(args.source)
    except (OSError, ValueError) as error:
        parser.exit(1, f"Site assembly failed: {error}\n")
    print(f"Built current sites and redirects in {output}")


if __name__ == "__main__":
    main()
